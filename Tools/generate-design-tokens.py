"""由 Design/tokens.json 生成 PhotoViewer/Core/Design/DesignTokens.g.cs。

生成到共享程序集（而非 PhotoViewer.Shared 源目录）：共享会话/视图模型（如 status.loading.delay）与四个头工程都能直接引用。

用法：
  python3 Tools/generate-design-tokens.py          # 重新生成
  python3 Tools/generate-design-tokens.py --check  # 只校验生成文件是否最新，不一致退出码 1

命名：令牌名按点分段，各段首字母大写后拼接（`motion.film.scroll.duration` → `MotionFilmScrollDuration`）。
平台覆盖值（`platforms`）中的数值另生成 `<名称><平台>` 常量（如 `FilterToggleWidthAndroid`）；语义色占位等非数值覆盖只写进注释。
单位映射：pt/ratio → double，ms/count → int，color → uint（0xAARRGGBB），其余字符串值 → string。只有推导式没有值的令牌不生成。
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Design" / "tokens.json"
TARGET = ROOT / "PhotoViewer" / "Core" / "Design" / "DesignTokens.g.cs"
PLATFORM_SUFFIX = {"windows": "Windows", "macos": "Mac", "ios": "IOS", "android": "Android"}


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("."))


def color_literal(value: str) -> str:
    digits = value.lstrip("#")
    if len(digits) == 6:
        digits = "FF" + digits
    if len(digits) != 8:
        raise ValueError(f"颜色值格式不合法：{value}")
    int(digits, 16)
    return f"0x{digits.upper()}u"


def literal(unit: str | None, value: object) -> tuple[str, str] | None:
    if value is None:
        return None
    if unit == "color" and isinstance(value, str) and value.startswith("#"):
        return "uint", color_literal(value)
    if isinstance(value, bool):
        raise ValueError(f"不支持布尔令牌：{value}")
    if unit in ("ms", "count") and isinstance(value, int):
        return "int", str(value)
    if isinstance(value, (int, float)):
        text = repr(float(value))
        return "double", text
    if isinstance(value, str):
        return "string", json.dumps(value, ensure_ascii=False)
    raise ValueError(f"不支持的令牌值：{value!r}")


def xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render(tokens: dict) -> str:
    lines = [
        "// <auto-generated>",
        "// 由 Tools/generate-design-tokens.py 从 Design/tokens.json 生成，请勿手改；改值先改 tokens.json 再重新生成。",
        "// </auto-generated>",
        "",
        "namespace PhotoViewer.Core.Design;",
        "",
        "/// <summary>设计令牌（L3 数值唯一来源 Design/tokens.json 的生成镜像）；pt 为逻辑点（macOS/iOS point、Windows DIP、Android dp）。</summary>",
        "public static class DesignTokens",
        "{",
    ]
    seen: dict[str, str] = {}

    def emit(name: str, token: str, kind: str, value: str, summary: str) -> None:
        if name in seen:
            raise ValueError(f"生成名冲突：{token} 与 {seen[name]} 都映射到 {name}")
        seen[name] = token
        lines.append(f"    /// <summary>{xml(summary)}</summary>")
        lines.append(f"    public const {kind} {name} = {value};")

    for token, body in sorted(tokens.items()):
        unit = body.get("unit")
        result = literal(unit, body.get("value"))
        if result is None:
            continue
        kind, value = result
        unit_text = f"（{unit}）" if unit else ""
        spec = body.get("spec")
        spec_text = f" {spec}" if spec else ""
        notes = []
        platforms = body.get("platforms") or {}
        semantic = {p: v for p, v in platforms.items() if isinstance(v, str) and not v.startswith("#")}
        if semantic:
            notes.append("平台语义：" + "，".join(f"{p}={v}" for p, v in sorted(semantic.items())))
        summary = f"{token}{unit_text}{spec_text}：{body.get('desc', '')}" + ("；" + "；".join(notes) if notes else "")
        emit(pascal(token), token, kind, value, summary)
        for platform, override in sorted(platforms.items()):
            if platform in semantic:
                continue
            suffix = PLATFORM_SUFFIX.get(platform)
            if suffix is None:
                raise ValueError(f"未知平台：{token}@{platform}")
            override_kind, override_value = literal(unit, override)  # type: ignore[misc]
            emit(pascal(token) + suffix, f"{token}@{platform}", override_kind, override_value,
                 f"{token}@{platform}{unit_text}：{platform} 平台差异值（见 Design/platforms.md）。")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="只校验生成文件是否最新")
    args = parser.parse_args()
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))["tokens"]
    output = render(tokens)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != output:
            print(f"{TARGET.relative_to(ROOT)} 与 tokens.json 不一致，请运行 python3 Tools/generate-design-tokens.py", file=sys.stderr)
            return 1
        print("DesignTokens.g.cs 已是最新")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output, encoding="utf-8")
    print(f"已生成 {TARGET.relative_to(ROOT)}（{output.count('public const')} 个常量）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
